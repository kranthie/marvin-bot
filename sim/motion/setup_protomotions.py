"""Add Marvin Bot to a ProtoMotions checkout: its MJCF, a retargeting URDF and a robot config.

ProtoMotions (github.com/NVlabs/ProtoMotions) trains motion-tracking policies from human motion
retargeted to a robot. Everything written here is generated from the description, so rerun this
after any change to it (as tools/build_urdf.py is rerun):

  protomotions/data/assets/mjcf/marvin_bot.xml      the robot for simulation: the URDF's links,
      inertias and collision boxes, a free base, and the motors' armature, friction and peak torque;
      the arms collide with the ground only
  protomotions/data/assets/urdf/for_retargeting/marvin_bot.urdf
      the URDF without visuals, plus the frames the retargeter matches human keypoints to: a toe
      15 cm ahead of each ankle, a hand frame on each wrist pitch axis pointing down the hand,
      and a torso frame (see TORSO_FRAME)
  protomotions/robot_configs/marvin_bot.py          joint gains, effort and speed limits, stance
      (palms turned in, MOTION_POSE),
      the bodies tracked, and registration in robot_configs/factory.py
  examples/experiments/mimic/mlp_bm_marvin_bot.py   the tracker: upstream's mlp_bm_l2c2.py
      (BeyondMimic) with the changes in EXPERIMENT_EDITS

The motors are ProtoMotions' built-in PD (no torque-speed curve, unlike the walking tasks).
Gains, armature and friction are robot_cfg.py's placeholders (sim/mujoco/joint_specs.py).

Usage (in the ProtoMotions environment, which has mujoco):
  python sim/motion/setup_protomotions.py /path/to/ProtoMotions
"""

