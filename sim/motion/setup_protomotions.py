def experiment(upstream: str) -> str:
    """The tracker experiment from upstream's text; stops if upstream has changed."""
    text = upstream
    for old, new in EXPERIMENT_EDITS:
        if text.count(old) != 1:
            sys.exit(f"{EXPERIMENT_UPSTREAM} has changed upstream; update EXPERIMENT_EDITS:\n{old}")
        text = text.replace(old, new)
    for old, new in EXPERIMENT_ALL:
        if old not in text:
            sys.exit(f"{EXPERIMENT_UPSTREAM} has changed upstream; update EXPERIMENT_ALL:\n{old}")
        text = text.replace(old, new)
    head = "# Generated by sim/motion/setup_protomotions.py (marvin-bot) from mlp_bm_l2c2.py.\n"
    return head + text


def mjcf(specs: dict) -> tuple[str, list[str]]:
    """The URDF as MJCF (collision boxes only, a free base, a motor per joint), and its joint
    order: MuJoCo's depth-first walk of the tree, which is the order of a motion's joint vector."""
    spec = mujoco.MjSpec.from_string(URDF.read_text())  # visuals are dropped by default
    spec.modelname = "marvin_bot"
    spec.body("pelvis").add_freejoint(name="root")
    order = [j.name for j in spec.joints if j.name in specs]
    for j in spec.joints:
        if j.name in specs:
            j.armature = specs[j.name]["armature"]
            j.frictionloss = specs[j.name]["friction"]
    # The arms collide with the ground only. Retargeted human arms pass close to the body, and
    # the hand boxes meet the thighs even with the arms hanging straight, which would let the
    # arms block the legs
    arms = [b.name for b in spec.bodies if b.name.startswith(ARMS)]
    for a in arms:
        for b in spec.bodies[1:]:
            if b.name != a and not (b.name in arms and b.name < a):
                spec.add_exclude(bodyname1=a, bodyname2=b.name)
    for name in order:
        effort = specs[name]["effort"]
        spec.add_actuator(
            name=name,
            target=name,
            trntype=mujoco.mjtTrn.mjTRN_JOINT,
            ctrlrange=[-effort, effort],
            ctrllimited=mujoco.mjtLimited.mjLIMITED_TRUE,
        )
    model = spec.compile()
    assert [model.joint(i).name for i in range(1, model.njnt)] == order
    return spec.to_xml(), order


def retargeting_urdf(order: list[str]) -> str:
    """The URDF without visuals, its joints in the MJCF's order (the retargeter's joint vector
    follows the URDF's joint order; retarget_marvin_bot.py checks), plus the keypoint frames."""
    text = re.sub(r"\s*<visual>.*?</visual>", "", URDF.read_text(), flags=re.S)
    text = re.sub(r'(link|parent link|child link)="torso_link"', r'\1="torso_body"', text)
    text = text.replace('<link name="torso_link">', '<link name="torso_body">')
    extra = []

    def fixed(name, parent, xyz, rpy=(0.0, 0.0, 0.0)):
        extra.append(
            f'  <link name="{name}"/>\n'
            f'  <joint name="{name}_joint" type="fixed"><parent link="{parent}"/>'
            f'<child link="{name}"/><origin xyz="{" ".join(map(str, xyz))}" '
            f'rpy="{" ".join(map(str, rpy))}"/></joint>\n'
        )

    for side in SIDES:
        fixed(f"{side}_toe_link", f"{side}_foot_link", (TOE, 0.0, 0.0))
        fixed(f"{side}_hand_link", f"{side}_palm_link", (0.0, 0.0, 0.0), (HAND, 0.0, 0.0))
    fixed("torso_link", "torso_body", TORSO_FRAME)
    joints = {
        m.group(1): m.group(0)
        for m in re.finditer(r'\s*<joint name="([^"]+)".*?</joint>', text, flags=re.S)
    }
    for block in joints.values():
        text = text.replace(block, "")
    ordered = "".join(joints[n] for n in order) + "\n"
    return text.replace("</robot>", ordered + "".join(extra) + "</robot>")


def config(specs: dict) -> str:
    robot = yaml.safe_load((DESC / "robot.yaml").read_text())
    control = {
        name: (s["kp"], s["kd"], round(s["effort"], 3), round(s["speed"], 3), s["armature"])
        for name, s in specs.items()
    }
    pose = {**robot["stance"], **MOTION_POSE}
    stance = {}
    for name in specs:
        key = name.split("_", 1)[1] if name.startswith(SIDES) else name
        if key in pose:
            stance[name] = round(math.radians(pose[key]), 4)
    return CONFIG.format(
        control=repr(control),
        stance=repr(stance),
        root_height=round(robot["stance_pelvis_height"] + 0.01, 3),
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("protomotions", type=Path, help="ProtoMotions checkout")
    root = ap.parse_args().protomotions
    pm = root / "protomotions"
    specs = joint_specs()
    model, order = mjcf(specs)
    out = {
        pm / "data/assets/mjcf/marvin_bot.xml": model,
        pm / "data/assets/urdf/for_retargeting/marvin_bot.urdf": retargeting_urdf(order),
        pm / "robot_configs/marvin_bot.py": config(specs),
        root / "examples/experiments/mimic/mlp_bm_marvin_bot.py": experiment(
            (root / EXPERIMENT_UPSTREAM).read_text()
        ),
    }
    for path, text in out.items():
        path.write_text(text)
        print(f"wrote {path}")
    factory = pm / "robot_configs/factory.py"
    text = factory.read_text()
    if '"marvin_bot"' not in text:
        anchor = "    else:\n        raise ValueError"
        factory.write_text(text.replace(anchor, FACTORY_BRANCH + anchor, 1))
        print(f"registered marvin_bot in {factory}")


if __name__ == "__main__":
    main()
