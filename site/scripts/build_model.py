"""Pack the generated robot model into one script file for the site's 3-D viewers.

Reads description/urdf/marvin_bot_covers.urdf (the robot with its shells) and marvin_bot.urdf (the
bare robot's masses), description/cad_model.yaml (each part's process, material and mass),
robot.yaml, skeleton.yaml, actuators.yaml and the part meshes in description/meshes/, which
`python -m cad.build` generates. Writes site/public/guide/model/marvin_model.js, which sets
window.MARVIN_MODEL: the joints, link masses, every visual part with its category and assembly
module, and the meshes, quantised and packed as base64. The code-CAD meshes are kept exact
(simplifying them breaks small holes and slots); only the dense hand meshes are simplified. The
meshes carry no normals: the viewers smooth them in the browser (site/src/scripts/marvin-render.js).
A script file rather than JSON, so the pages also work when opened straight from disk.

    pip install -e ".[cad,hand]" && python -m cad.build && python site/scripts/build_model.py

The meshes are derived from the hardware design files (CERN-OHL-S-2.0); the hand meshes from the
AmazingHand by Pollen Robotics (CC-BY-4.0).
"""

from __future__ import annotations

import argparse
import base64
import json
import math
import xml.etree.ElementTree as ET
from pathlib import Path

import fast_simplification
import numpy as np
import trimesh
import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "site" / "public" / "guide" / "model" / "marvin_model.js"
HAND_KEEP = 0.4  # fraction of the AmazingHand meshes' triangles kept
SOURCE = (
    "Generated by site/scripts/build_model.py from the Marvin Bot repository: description/urdf/, "
    "description/cad_model.yaml and the code-CAD part meshes (CERN-OHL-S-2.0). Hand meshes: "
    "AmazingHand by Pollen Robotics, CC-BY-4.0."
)


def floats(text: str | None, n: int = 3) -> list[float]:
    return [float(v) for v in text.split()] if text else [0.0] * n


def rpy_matrix(r: float, p: float, y: float) -> np.ndarray:
    cr, sr, cp, sp, cy, sy = (
        math.cos(r),
        math.sin(r),
        math.cos(p),
        math.sin(p),
        math.cos(y),
        math.sin(y),
    )
    return np.array(
        [
            [cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
            [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
            [-sp, cp * sr, cp * cr],
        ]
    )


def transform(xyz: list[float], rpy: list[float]) -> np.ndarray:
    t = np.eye(4)
    t[:3, :3] = rpy_matrix(*rpy)
    t[:3, 3] = xyz
    return t


def parse_urdf(path: Path) -> tuple[dict, list[dict]]:
    root = ET.parse(path).getroot()
    links, joints = {}, []
    for link in root.findall("link"):
        inertial = link.find("inertial")
        ine = None
        if inertial is not None:
            o = inertial.find("origin")
            ine = {
                "mass": float(inertial.find("mass").get("value")),
                "com": floats(o.get("xyz") if o is not None else None),
            }
        visuals = []
        for v in link.findall("visual"):
            o, geom, mat = v.find("origin"), v.find("geometry")[0], v.find("material")
            colour = mat.find("color") if mat is not None else None
            visuals.append(
                {
                    "xyz": floats(o.get("xyz") if o is not None else None),
                    "rpy": floats(o.get("rpy") if o is not None else None),
                    "geom": geom.tag,
                    "attrib": dict(geom.attrib),
                    "mat": mat.get("name") if mat is not None else "",
                    "rgba": floats(colour.get("rgba"), 4)
                    if colour is not None
                    else [0.6] * 3 + [1],
                }
            )
        links[link.get("name")] = {"inertial": ine, "visuals": visuals}
    for j in root.findall("joint"):
        o, lim = j.find("origin"), j.find("limit")
        joints.append(
            {
                "name": j.get("name"),
                "parent": j.find("parent").get("link"),
                "child": j.find("child").get("link"),
                "xyz": floats(o.get("xyz") if o is not None else None),
                "rpy": floats(o.get("rpy") if o is not None else None),
                "axis": floats(j.find("axis").get("xyz")),
                "lower": float(lim.get("lower")),
                "upper": float(lim.get("upper")),
                "effort": float(lim.get("effort")),
                "velocity": float(lim.get("velocity")),
            }
        )
    return links, joints


def module_of(link: str, cat: str) -> str:
    """The assembly module a part belongs to (docs/design/assembly_wiring.md)."""
    if cat == "cover":
        return "cover"
    if cat == "battery":
        return "battery"
    if link == "pelvis":
        return "pelvis"
    if link in ("neck_link", "head_link"):
        return "head"
    if any(k in link for k in ("hip", "thigh", "shin", "ankle", "foot")):
        return "leg"
    if any(k in link for k in ("shoulder", "arm", "wrist", "palm")):
        return "arm"
    return "torso"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    desc = ROOT / "description"
    cad = yaml.safe_load((desc / "cad_model.yaml").read_text())
    robot = yaml.safe_load((desc / "robot.yaml").read_text())
    skel = yaml.safe_load((desc / "skeleton.yaml").read_text())
    acts = yaml.safe_load((desc / "actuators.yaml").read_text())
    links, joints = parse_urdf(desc / "urdf" / "marvin_bot_covers.urdf")
    bare, _ = parse_urdf(desc / "urdf" / "marvin_bot.urdf")
    root = (set(links) - {j["child"] for j in joints}).pop()

    # world transforms at the zero pose, to give each motor outline the joint it drives
    world = {root: np.eye(4)}
    pending = list(joints)
    while pending:
        for j in list(pending):
            if j["parent"] in world:
                world[j["child"]] = world[j["parent"]] @ transform(j["xyz"], j["rpy"])
                pending.remove(j)
    joint_pos = {j["name"]: world[j["child"]][:3, 3] for j in joints}
    motor_of: dict[str, str] = {}
    for m in robot["motors"]:
        for side in ["left", "right"] if "{side}" in m["name"] else [None]:
            for d in m["drives"]:
                motor_of.setdefault(d.replace("{side}", side) if side else d, m["model"])

    def nearest_joint(link: str, xyz: list[float], model: str) -> str:
        if "shin" in link and model == "RS03":  # the two calf motors drive the ankle linkage
            return link.replace("shin_link", "ankle_pitch")
        pos = (world[link] @ np.r_[xyz, 1])[:3]
        cands = [n for n, mm in motor_of.items() if mm == model]
        return min(cands, key=lambda n: float(np.linalg.norm(joint_pos[n] - pos)))

    def side_key(link: str, size) -> tuple:
        generic = link.replace("left_", "{s}_").replace("right_", "{s}_")
        return generic, tuple(round(x, 4) for x in size)

    budget_boxes = {
        side_key(b["link"], b["size"]): b
        for b in skel["bodies"]
        if b["budget"] in ("compute", "battery", "keep_alive", "padding")
    }
    box_names = {
        "compute": "Jetson AGX Orin developer kit (outline)",
        "battery": "13S3P battery pack (outline)",
        "keep_alive": "keep-alive battery (outline)",
        "padding": "fall padding",
    }

    meshes = {}
    total = 0
    for link in links.values():
        for v in link["visuals"]:
            if v["geom"] == "mesh":
                stem = Path(v["attrib"]["filename"]).stem
                meshes[stem] = trimesh.load(desc / "meshes" / f"{stem}.stl")
                total += len(meshes[stem].faces)

    blob = bytearray()

    def add(arr: np.ndarray) -> int:
        while len(blob) % 4:
            blob.append(0)
        off = len(blob)
        blob.extend(arr.tobytes())
        return off

    parts = []
    for lname, link in links.items():
        for v in link["visuals"]:
            p = {"link": lname, "xyz": v["xyz"], "rpy": v["rpy"], "rgba": v["rgba"]}
            mat = v["mat"]
            if v["geom"] == "mesh":
                stem = Path(v["attrib"]["filename"]).stem
                info = cad.get(stem, {})
                proc = info.get("process", "bought")
                if stem.startswith("elec_imu") or stem == "head_camera":
                    cat = "sensors"
                elif stem.startswith("elec_"):
                    cat = "electronics"
                elif stem.endswith("_hand"):
                    cat = "hands"
                elif proc == "cover" or stem.endswith("_cover"):
                    cat = "cover"
                elif proc in ("cnc", "service", "print"):
                    cat = proc
                else:
                    cat = "bought"
                verts = np.asarray(meshes[stem].vertices, dtype=np.float64)
                faces = np.asarray(meshes[stem].faces, dtype=np.int64)
                if stem.endswith("_hand"):  # dense scanned-style meshes; the code-CAD stays exact
                    v2, f2 = fast_simplification.simplify(
                        verts.astype(np.float32), faces.astype(np.int32), 1 - HAND_KEEP
                    )
                    verts, faces = v2.astype(np.float64), f2.astype(np.int64)
                lo = verts.min(0)
                span = np.maximum(verts.max(0) - lo, 1e-6)
                q = np.round((verts - lo) / span * 65535).astype(np.uint16)
                idx = faces.astype(np.uint16 if len(verts) < 65536 else np.uint32)
                p.update(
                    kind="mesh",
                    name=stem,
                    cat=cat,
                    material=info.get("material", mat),
                    process=proc,
                    mass=info.get("mass"),
                    budget=info.get("budget"),
                    lo=lo.round(6).tolist(),
                    span=span.round(6).tolist(),
                    v=[add(q), len(verts)],
                    i=[add(idx), len(faces) * 3, idx.itemsize],
                )
            elif v["geom"] == "box":
                size = floats(v["attrib"]["size"])
                b = budget_boxes.get(side_key(lname, size))
                kind = b["budget"] if b else "box"
                cat = {"compute": "compute", "battery": "battery", "keep_alive": "battery"}.get(
                    kind, "padding" if b else "bought"
                )
                p.update(
                    kind="box",
                    size=size,
                    cat=cat,
                    name=box_names.get(kind, "box"),
                    mass=b["mass"] if b else None,
                    budget=kind,
                )
                if mat in acts:  # the Feetech servos are drawn as boxes
                    p.update(
                        cat="actuator",
                        name=f"{mat} servo",
                        model=mat,
                        joint=nearest_joint(lname, v["xyz"], mat),
                    )
            else:  # cylinder: a RobStride motor's body or driver cap
                model = mat if mat in acts else "motor"
                p.update(
                    kind="cyl",
                    r=float(v["attrib"]["radius"]),
                    len=float(v["attrib"]["length"]),
                    cat="actuator",
                    name=f"{model} actuator",
                    model=model,
                    joint=nearest_joint(lname, v["xyz"], model),
                )
            p["module"] = module_of(lname, p["cat"])
            parts.append(p)

    model = {
        "root": root,
        "joints": joints,
        "inertia": {n: bare[n]["inertial"] for n in bare},
        "parts": parts,
        "actuators": {
            k: {
                f: acts[k][f]
                for f in ("peak_torque", "rated_torque", "no_load_speed_rpm", "gear_ratio", "mass")
            }
            for k in ("RS04", "RS03", "RS06", "RS00", "STS3250")
        },
        "motor_of": motor_of,
        "coupled": robot.get("coupled_limits", []),
        "stance": robot["stance"],
        "pelvis_height": robot["stance_pelvis_height"],
        "source": SOURCE,
        "bin": base64.b64encode(bytes(blob)).decode(),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(model, separators=(",", ":"))
    args.out.write_text(f"/* Marvin Bot 3-D model data. {SOURCE} */\nwindow.MARVIN_MODEL={body};\n")
    print(f"{len(parts)} parts, {total} triangles in, {len(blob) / 1e6:.2f} MB -> {args.out}")


if __name__ == "__main__":
    main()
