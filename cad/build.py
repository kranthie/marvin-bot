"""Build the code-CAD parts: meshes, mass properties and a manufacturability check.

Writes:
  description/meshes/<part>.stl   each part in its link's frame (m), for the URDF's visuals
  description/cad_model.yaml      per part: link, material, process, mass budget item, mass,
                                  centre of mass and inertia (link frame, SI), size (mm)

tools/build_urdf.py takes the CAD parts' masses and inertias in place of skeleton.yaml's
estimates for the budget items they cover (leg structure, feet, pelvis, torso), and shows their
meshes.

Checks that machined parts fit the desktop mill (MILL_MM, the usable area with the tool
changer, and stock thickness) and printed parts fit the printer (PRINT_MM); parts that don't
are listed to be split. Parts marked "service" (flat plates cut by an online laser or water-jet
service) are not size-checked.

Usage:
  python -m cad.build            # write meshes and cad_model.yaml, print the part table
  python -m cad.build --check    # exit 1 if cad_model.yaml is out of date (CI)

Needs: pip install -e ".[cad]"
"""

import argparse
import difflib
import sys
from pathlib import Path

import numpy as np
import trimesh
import yaml

from . import arm, covers, electrical, head, leg, torso

ROOT = Path(__file__).resolve().parent.parent
MESHES = ROOT / "description" / "meshes"
MODEL = ROOT / "description" / "cad_model.yaml"
MILL_MM = (200.0, 150.0, 60.0)  # usable X, Y, stock thickness (mm), with the tool changer fitted
PRINT_MM = (250.0, 250.0, 250.0)
BUDGET = {
    "elec_": "electronics",  # first: electronics names also name their bay
    "foot": "feet",
    "pelvis": "pelvis",
    "torso": "torso",
    "shoulder": "arm_structure",
    "upper_arm": "arm_structure",
    "forearm": "arm_structure",
    "gripper": "grippers",
    "neck": "head",
    "head": "head",
}  # name keyword -> budget item; else legs


def budget_item(p) -> str:
    if p.process == "cover":
        return "covers"  # add-on, outside the mass budget and the default URDF
    return next((v for k, v in BUDGET.items() if k in p.name), "leg_structure")


def fits(size: np.ndarray, limit) -> bool:
    return all(
        a <= b for a, b in zip(sorted(size, reverse=True), sorted(limit, reverse=True), strict=True)
    )


def r6(v) -> list[float]:
    return [float(f"{x:.6g}") + 0.0 for x in np.ravel(v)]


def build() -> tuple[str, dict, list]:
    parts = (
        leg.all_parts()
        + torso.parts()
        + arm.all_parts()
        + head.parts()
        + electrical.parts()
        + covers.all_parts()
    )
    model, meshes, too_big = {}, {}, []
    for p in parts:
        mass, com, inertia = p.mass_properties()
        size = p.bounds()
        limit = (
            MILL_MM if p.process == "cnc" else PRINT_MM if p.process in ("print", "cover") else None
        )
        if limit and not fits(size, limit):
            too_big.append((p.name, p.process, size))
        model[p.name] = dict(
            link=p.link,
            material=p.material,
            process=p.process,
            budget=budget_item(p),
            mass=round(float(mass), 5),
            com=r6(com),
            inertia=r6(inertia[[0, 1, 2, 0, 0, 1], [0, 1, 2, 1, 2, 2]]),
            size_mm=[round(float(x), 1) for x in size],
        )
        v, f = p.mesh()
        meshes[p.name] = trimesh.Trimesh(v / 1000, f)
    header = (
        "# Generated by cad/build.py from the code-CAD parts in cad/. Do not edit.\n"
        "# Per part: mass (kg), centre of mass and inertia about it (ixx iyy izz ixy ixz iyz,\n"
        "# link frame, SI), size (mm), and the mass budget item it covers.\n"
    )
    text = header + yaml.safe_dump(model, sort_keys=False, width=100, default_flow_style=None)
    return text, meshes, too_big


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text, meshes, too_big = build()
    if args.check:
        if not MODEL.exists() or MODEL.read_text() != text:
            print("description/cad_model.yaml is out of date: run python -m cad.build")
            old = MODEL.read_text().splitlines() if MODEL.exists() else []
            diff = difflib.unified_diff(old, text.splitlines(), "committed", "built", n=1)
            print("\n".join(list(diff)[:40]))
            return 1
        if too_big:
            print(f"parts too big for the mill or printer: {[n for n, _, _ in too_big]}")
            return 1
        print("cad_model.yaml up to date; every part fits the mill or the printer")
        return 0
    MESHES.mkdir(parents=True, exist_ok=True)
    for old in MESHES.glob("*.stl"):
        old.unlink()
    for name, m in meshes.items():
        m.export(MESHES / f"{name}.stl")
    MODEL.write_text(text)
    model = yaml.safe_load(text)
    by_item: dict[str, float] = {}
    print(f"{'part':28} {'process':7} {'material':8} {'mass g':>7} {'size mm':>18}")
    for name, p in model.items():
        by_item[p["budget"]] = by_item.get(p["budget"], 0.0) + p["mass"]
        s = p["size_mm"]
        size = f"{s[0]:5.0f} x{s[1]:4.0f} x{s[2]:4.0f}"
        print(f"{name:28} {p['process']:7} {p['material']:8} {p['mass'] * 1000:7.1f} {size}")
    print(
        "\nmass by budget item (both legs): "
        + ", ".join(f"{k} {v:.3f} kg" for k, v in by_item.items())
    )
    if too_big:
        print(
            "\ntoo big for the desktop mill or printer (split, or order from a machining service):"
        )
        for name, process, size in too_big:
            print(f"  {name:28} {process:5} {size[0]:.0f} x {size[1]:.0f} x {size[2]:.0f} mm")
    print(
        f"\nwrote {len(meshes)} meshes to {MESHES.relative_to(ROOT)} and {MODEL.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
